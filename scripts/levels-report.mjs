#!/usr/bin/env node
// Builds docs/levels-report.md from the level checker's results (.levels/*.json, written by
// `vitest run -c vitest.levels.config.ts`). Exits with an error if any level is missing or failed.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const WORLDS = ['forest', 'castle', 'mountains', 'desert', 'frozen', 'volcano'];
const TRAP_CAP = 80;
const rows = [];
let failed = 0;
for (const w of WORLDS) {
  const f = `.levels/${w}.json`;
  if (!existsSync(f)) {
    console.error(`missing ${f}`);
    failed++;
    continue;
  }
  rows.push(...JSON.parse(readFileSync(f, 'utf8')));
}
rows.sort((a, b) => a.index - b.index);
const shot = (s) => `${s.ammo} → ${s.target}`;
const lines = [
  '# Level report',
  '',
  'Generated by the level checker (`npm run levels:check`). Bots play every level as a real duel with the',
  'game\'s own physics and rules (fixed 60 Hz step, rival turns and rival AI included):',
  '',
  '- **Sharp bot:** every turn it tries every candidate shot on a copy of the game (aimed at the rival\'s head',
  '  and body, every rope, every named body and the water, flat and lobbed, several speeds, every ammo it has)',
  '  and plays the best one for real. Its real playthrough proves the level can be won; it is replayed from',
  '  scratch before it counts, and the e2e tests replay it in the browser.',
  '- **Human bots:** the same choices with a player\'s aim errors (σ 0.03 rad, σ 3.5 % power, sometimes the',
  '  second-best idea), 5 runs with different seeds.',
  '- **Trap cap:** every candidate shot measures the damage the environment did to each fighter in that one',
  `  shot. It must never exceed ${TRAP_CAP}, so a trap alone never K.O.s a fighter at full HP (100).`,
  '',
  `${rows.length} levels checked. Rules: the sharp bot wins; max trap damage per shot ≤ ${TRAP_CAP}; winning duels last`,
  'at least 4 player shots on average.',
  '',
  '| # | Level | Rival HP | AI skill | Sharp bot | Human bots won | Avg shots (wins) | Max trap / shot | Best trap on rival | Sims |',
  '|---|---|---|---|---|---|---|---|---|---|',
];
let totalShots = 0;
let totalWins = 0;
for (const r of rows) {
  const name = `${r.id}${r.boss ? ' (boss)' : ''}${r.tricky ? ' (tricky)' : ''}${r.wind ? ` wind ${r.wind}` : ''}`;
  const ok = !!r.solution && r.maxTrap <= TRAP_CAP && r.avgShots >= 4;
  if (!ok) failed++;
  const s = r.sharp;
  const sharp = s.win ? `won in ${s.shots.length} shots, ${s.playerHp} HP left, ${s.stars}★${s.trapKill ? ' (trap K.O.)' : ''}` : '**lost**';
  const hw = r.humans.filter((h) => h.win);
  for (const w of [s, ...r.humans].filter((x) => x.win)) {
    totalShots += w.shots.length;
    totalWins++;
  }
  const trap = r.bestTrap.damage ? `${Math.round(r.bestTrap.damage)} (${r.bestTrap.target})` : '—';
  lines.push(`| ${r.index} | ${name} | ${r.rivalHp} | ${r.skill.toFixed(2)} | ${sharp} | ${hw.length}/${r.humans.length} | ${r.avgShots.toFixed(1)}${r.avgShots < 4 ? ' **< 4**' : ''} | ${Math.round(r.maxTrap)}${r.maxTrap > TRAP_CAP ? ' **> 80**' : ''} | ${trap} | ${r.sims} |`);
}
lines.push('', `Average over all winning duels: ${(totalShots / Math.max(1, totalWins)).toFixed(1)} player shots.`, '');
lines.push('', '## Sharp bot playthroughs', '');
for (const r of rows) if (r.solution) lines.push(`- **${r.id}:** ${r.solution.map(shot).join(' · ')}`);
lines.push('', failed ? `**${failed} level(s) failed.**` : 'All levels pass.', '');
writeFileSync('docs/levels-report.md', lines.join('\n'));
// machine-readable: the sharp bot's winning shots (the e2e tests replay them)
writeFileSync('docs/levels-report.json', JSON.stringify(rows.map((r) => ({ id: r.id, rivalHp: r.rivalHp, solution: r.solution, avgShots: r.avgShots, maxTrap: r.maxTrap })), null, 1) + '\n');
console.info(`docs/levels-report.md: ${rows.length} levels, ${failed} failed`);
if (failed) process.exit(1);
