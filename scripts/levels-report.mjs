#!/usr/bin/env node
// Builds docs/levels-report.md from the level checker's results (.levels/*.json, written by
// `vitest run -c vitest.levels.config.ts`). Exits with an error if any level is missing or failed.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const WORLDS = ['forest', 'castle', 'mountains', 'desert', 'frozen', 'volcano'];
const rows = [];
let failed = 0;
for (const w of WORLDS) {
  const f = `.levels/${w}.json`;
  if (!existsSync(f)) {
    console.error(`missing ${f}`);
    failed++;
    continue;
  }
  rows.push(...JSON.parse(readFileSync(f, 'utf8')));
}
rows.sort((a, b) => a.index - b.index);
const shot = (s) => `${s.ammo} → ${s.target} (${(s.angle * 57.2958).toFixed(1)}°, ${Math.round(s.power * 100)}%)`;
const lines = [
  '# Level report',
  '',
  'Generated by the level checker (`npm run levels:check`): a bot that plays every level with the real game',
  'physics and rules (fixed 60 Hz step, seed 1, rival turns included). It tries every candidate first shot',
  '(aimed at each rope, body and the rival with flat and lobbed arcs at several speeds, plus a grid of angles and',
  'powers, for every ammo type), then searches the most promising states for a win within par. Every win is',
  'replayed from scratch before it counts. "Direct only" plays every shot at the rival\'s head; "Direct max" is',
  'the most damage direct hits could ever do with all of the level\'s ammo.',
  '',
  `${rows.length} levels checked. Rules: a win within par everywhere; no one-shot win from level 4 on (par 2–3);`,
  'direct hits alone never win from level 3 on.',
  '',
  '| # | Level | Par | Shots | Rival HP | Winning shots found | One-shot win | Direct only | Direct max | Sims |',
  '|---|---|---|---|---|---|---|---|---|---|',
];
for (const r of rows) {
  const name = `${r.id}${r.boss ? ' (boss)' : ''}${r.tricky ? ' (tricky)' : ''}${r.wind ? ` wind ${r.wind}` : ''}`;
  const sol = r.solution ? r.solution.map(shot).join('<br>') : '**none**';
  const ok = r.solution && r.solution.length <= r.par && (r.index <= 3 || !r.oneShot) && (r.index <= 2 || !r.directOnly.win);
  if (!ok) failed++;
  lines.push(`| ${r.index} | ${name} | ${r.par} | ${r.shots} | ${r.rivalHp} | ${sol} | ${r.oneShot ? (r.index <= 3 ? 'yes (allowed)' : '**yes**') : 'none'} | ${r.directOnly.win ? '**wins**' : `fails (${Math.round(r.directOnly.damage)} dmg)`} | ${Math.round(r.directBound)} | ${r.sims} |`);
}
lines.push('', failed ? `**${failed} level(s) failed.**` : 'All levels pass.', '');
writeFileSync('docs/levels-report.md', lines.join('\n'));
// machine-readable: the proven solutions (the e2e tests replay some of them)
writeFileSync('docs/levels-report.json', JSON.stringify(rows.map((r) => ({ id: r.id, par: r.par, rivalHp: r.rivalHp, solution: r.solution, oneShot: !!r.oneShot, directOnly: r.directOnly.win })), null, 1) + '\n');
console.info(`docs/levels-report.md: ${rows.length} levels, ${failed} failed`);
if (failed) process.exit(1);
